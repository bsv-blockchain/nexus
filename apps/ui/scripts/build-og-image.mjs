#!/usr/bin/env node
/**
 * Renders public/og-image.png (1200x630) from the template in
 * og-image.html.mjs using headless Chrome.
 *
 * Rendered at 2x and downsampled so text and the store badges stay crisp
 * in feed previews.
 *
 *   node scripts/build-og-image.mjs
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildOgHtml } from "./og-image.html.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "public/og-image.png");
const versionFile = join(root, "lib/og-image-version.ts");

/** Puppeteer's chrome-headless-shell, if a version has been cached. */
function puppeteerHeadlessShells() {
  const base = join(homedir(), ".cache/puppeteer/chrome-headless-shell");
  if (!existsSync(base)) return [];
  return readdirSync(base)
    .sort()
    .reverse()
    .flatMap((version) =>
      readdirSync(join(base, version)).map((platform) =>
        join(base, version, platform, "chrome-headless-shell")
      )
    );
}

// chrome-headless-shell first: the full Chrome app hangs on --screenshot
const chromeCandidates = [
  ...puppeteerHeadlessShells(),
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
];

const chrome = chromeCandidates.find((path) => existsSync(path));
if (!chrome) {
  console.error("No Chrome/Chromium binary found. Checked:");
  for (const path of chromeCandidates) console.error(`  ${path}`);
  process.exit(1);
}

const work = mkdtempSync(join(tmpdir(), "nexus-og-"));
const htmlPath = join(work, "og.html");
const rawPath = join(work, "og-2x.png");

try {
  /* Copy is read out of the product's own content table rather than
     duplicated here, so the card cannot say something the app does not. */
  const contentSrc = readFileSync(join(root, "lib/data/content.ts"), "utf8");
  const field = (key) => {
    const match = contentSrc.match(
      new RegExp(`${key}:\\s*\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`)
    );
    if (!match) throw new Error(`content.ts: could not read brand.${key}`);
    return match[1];
  };
  const brand = {
    name: field("name"),
    tagline: field("tagline"),
    description: field("description"),
  };
  console.log(`Copy: ${brand.tagline}`);

  writeFileSync(htmlPath, buildOgHtml(root, brand));

  const isHeadlessShell = chrome.endsWith("chrome-headless-shell");

  execFileSync(
    chrome,
    [
      ...(isHeadlessShell ? [] : ["--headless=new"]),
      "--disable-gpu",
      "--hide-scrollbars",
      "--no-sandbox",
      `--user-data-dir=${join(work, "profile")}`,
      "--window-size=1200,630",
      "--force-device-scale-factor=2",
      "--virtual-time-budget=4000",
      `--screenshot=${rawPath}`,
      `file://${htmlPath}`,
    ],
    { stdio: "pipe" }
  );

  // 2400x1260 -> 1200x630
  execFileSync("sips", ["-z", "630", "1200", rawPath, "--out", output]);

  const size = execFileSync("sips", [
    "-g",
    "pixelWidth",
    "-g",
    "pixelHeight",
    output,
  ]).toString();

  /* Stamp a content hash into lib/og-image-version.ts. metadata.ts appends
     it to og:image as ?v=<hash>, which is the only way to invalidate
     Slack's ~24h link-preview cache — Slack has no manual purge tool, and
     unlike X and LinkedIn it will not re-fetch an unchanged URL. Deriving
     the hash here means the bust happens whenever the image actually
     changes, and never when it does not. */
  const hash = createHash("sha256")
    .update(readFileSync(output))
    .digest("hex")
    .slice(0, 8);

  writeFileSync(
    versionFile,
    `/* Generated by scripts/build-og-image.mjs — do not edit by hand.\n` +
      `   Run \`npm run build:og\` to regenerate. */\n\n` +
      `export const OG_IMAGE_VERSION = "${hash}";\n`
  );

  console.log(`Wrote ${output}`);
  console.log(size.trim());
  console.log(`Cache-bust version: ${hash}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
